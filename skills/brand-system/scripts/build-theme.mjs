#!/usr/bin/env node
// tokens.json -> theme.css. Zero dependencies.
//
//   node build-theme.mjs brand/tokens.json brand/theme.css
//
// Every leaf with a $value becomes a CSS custom property named from its path:
//   color.brand.primary -> --color-brand-primary
// Aliases like "{color.brand.700}" stay aliases: they become var(--color-brand-700).
// A top-level "dark" group mirrors the other groups and is emitted as the dark theme
// (prefers-color-scheme: dark, or <html data-theme="dark">). A top-level "fontImport"
// token holding a Google Fonts CSS URL becomes an @import line.
// Exit code 1 when an alias points at a token that does not exist.
import { readFileSync, writeFileSync } from "node:fs";

const [, , inPath, outPath] = process.argv;
if (!inPath || !outPath) {
  console.error("usage: build-theme.mjs <tokens.json> <theme.css>");
  process.exit(2);
}

const tokens = JSON.parse(readFileSync(inPath, "utf8"));

function leaves(node, path = []) {
  if (node && typeof node === "object" && "$value" in node) return [[path, node.$value]];
  if (!node || typeof node !== "object") return [];
  return Object.entries(node)
    .filter(([k]) => !k.startsWith("$"))
    .flatMap(([k, v]) => leaves(v, [...path, k]));
}

const names = new Set(leaves(tokens).map(([p]) => p.join(".")));
const missing = [];

function fmt(value) {
  if (Array.isArray(value)) return value.map((f) => (/[\s,]/.test(f) && !/^["']/.test(f) ? `"${f}"` : f)).join(", ");
  if (value && typeof value === "object" && "value" in value && "unit" in value) return `${value.value}${value.unit}`;
  if (typeof value === "string") {
    return value.replace(/\{([^}]+)\}/g, (_, ref) => {
      if (!names.has(ref)) missing.push(ref);
      return `var(--${ref.replaceAll(".", "-")})`;
    });
  }
  return String(value);
}

const decl = (path, value) => `  --${path.join("-")}: ${fmt(value)};`;

const { fontImport, dark, ...rest } = tokens;
const light = leaves(rest).map(([p, v]) => decl(p, v));
const darkDecls = dark ? leaves(dark).map(([p, v]) => decl(p, v)) : [];

let css = `/* Generated by graphic-skills build-theme from ${inPath.split(/[\\/]/).pop()}. Edit the tokens, not this file. */\n`;
if (fontImport?.$value) css += `@import url("${fontImport.$value}");\n`;
css += `\n:root {\n${light.join("\n")}\n}\n`;
if (darkDecls.length) {
  css += `\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${darkDecls.map((d) => "  " + d).join("\n")}\n  }\n}\n`;
  css += `\n:root[data-theme="dark"] {\n${darkDecls.join("\n")}\n}\n`;
}

writeFileSync(outPath, css);
const unique = [...new Set(missing)];
if (unique.length) {
  console.error(`Unresolved token references: ${unique.join(", ")}`);
  process.exit(1);
}
console.log(`wrote ${outPath}: ${light.length} tokens${darkDecls.length ? `, ${darkDecls.length} dark overrides` : ""}`);
